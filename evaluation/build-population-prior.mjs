import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { buildPopulationPrior, DEFAULT_PREDICTOR_CONFIG } from "../model.mjs";
import { parseZ8rjx } from "./evaluate.mjs";

const dataPath = resolve(process.argv[2] ?? "/tmp/human-binary-dat.csv");
const outputPath = resolve(process.argv[3] ?? new URL("../population-prior.mjs", import.meta.url).pathname);
const manifestPath = new URL("split-manifest.json", import.meta.url);
const dataBytes = await readFile(dataPath);
const manifestBytes = await readFile(manifestPath);
const manifest = JSON.parse(manifestBytes);
const participants = parseZ8rjx(dataBytes.toString("utf8"));
const sequences = manifest.train.map((id) => {
  const participant = participants.get(id);
  if (!participant) throw new Error(`Training participant ${id} is absent`);
  return participant.sequence;
});
const maxContext = DEFAULT_PREDICTOR_CONFIG.maxContext;
const prior = buildPopulationPrior(sequences, maxContext);
const values = new Uint32Array(2 * (2 ** (maxContext + 1) - 1));
let offset = 0;
for (let order = 0; order <= maxContext; order += 1) {
  for (let index = 0; index < 2 ** order; index += 1) {
    const key = order === 0
      ? "*"
      : index.toString(2).padStart(order, "0").replaceAll("0", "d").replaceAll("1", "f");
    const counts = prior.orders[order][key] ?? { f: 0, d: 0 };
    values[offset++] = counts.f;
    values[offset++] = counts.d;
  }
}
const packed = Buffer.alloc(values.length * 4);
values.forEach((value, index) => packed.writeUInt32LE(value, index * 4));
const metadata = {
  version: 1,
  source: "Top-Down Control in Random Choice (OSF z8rjx)",
  sourceUrl: "https://osf.io/z8rjx/",
  sourceFile: "Experimental Data/dat.csv",
  sourceSha256: createHash("sha256").update(dataBytes).digest("hex"),
  splitManifestSha256: createHash("sha256").update(manifestBytes).digest("hex"),
  partition: "train",
  participants: sequences.length,
  observationsPerParticipant: 1000,
  maxContext,
  complementSymmetrized: true,
  packedCountsSha256: createHash("sha256").update(packed).digest("hex"),
};
const source = `// Generated by evaluation/build-population-prior.mjs. Do not edit by hand.\nimport { decodePopulationPrior } from "./population-prior-codec.mjs";\n\nexport const POPULATION_PRIOR_METADATA = Object.freeze(${JSON.stringify(metadata, null, 2)});\n\nconst PACKED_COUNTS_BASE64 =\n  ${JSON.stringify(packed.toString("base64"))};\n\nexport const POPULATION_PRIOR = decodePopulationPrior(\n  PACKED_COUNTS_BASE64,\n  POPULATION_PRIOR_METADATA.maxContext,\n);\n`;
await writeFile(outputPath, source);
console.log(JSON.stringify({ outputPath, ...metadata }, null, 2));
